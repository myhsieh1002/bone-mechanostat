% exportFiguresJTB  Export the model-generated figures to the JTB numbering.
%
%   Copy of experiments/exportFiguresPLOSONE.m with one change: the job table.
%   The JTB manuscript opens with a schematic (Fig 1, drawn by
%   fig1_schematic.py in the submission folder, not from model output), so
%   every model figure moves down by one, and the dose-response figure moves
%   to the end of the Results because it is where the model disagrees with
%   experiment:
%
%          E0_baseline         Fig1 (PLOS ONE)  ->  Fig2
%          E2_calciumLoading   Fig3             ->  Fig3
%          E5_siteSpecificity  Fig4             ->  Fig4
%          E3_unloading        Fig5             ->  Fig5
%          E4_pharmacology     Fig6             ->  Fig6
%          E1_doseResponse     Fig2             ->  Fig7
%          E6_bifurcation      Fig7             ->  Fig8
%
%   The images are bit-identical to the PLOS ONE submission; only the file
%   names differ.  Canvas limit stays at 174 mm / 300 dpi / LZW / 8 pt.
%
%   To keep the "every figure is regenerated by a single named script" claim
%   true, add this file to experiments/ in the repository and tag the release
%   (v2.26) before submission.
%
%   Project: bone-mechanostat (PROJECT_PLAN v2.25)

plosFontMin = 8;
plosDPI     = 300;
plosMaxW    = 2055;     % px  (174 mm)
plosMaxH    = 2763;     % px  (234 mm)

plosJobs = ["E0_baseline"        "Fig2"
            "E2_calciumLoading"  "Fig3"
            "E5_siteSpecificity" "Fig4"
            "E3_unloading"       "Fig5"
            "E4_pharmacology"    "Fig6"
            "E1_doseResponse"    "Fig7"
            "E6_bifurcation"     "Fig8"];

plosOutDir = getResultsDir("figures_jtb");
plosReport = strings(size(plosJobs, 1), 1);
plosProbe  = fullfile(tempdir, "jtb_probe.tif");

for plosK = 1:size(plosJobs, 1)
    plosFig = runExperimentFigure(plosJobs(plosK, 1));
    plosOut = fullfile(plosOutDir, plosJobs(plosK, 2) + ".tif");

    exportgraphics(plosFig, plosProbe, Resolution = plosDPI);
    plosNative = imfinfo(plosProbe);
    plosScale = min([plosMaxW / plosNative.Width, plosMaxH / plosNative.Height, 1]);
    plosFont  = plosFontMin / plosScale;

    fontsize(plosFig, plosFont, "points");
    exportgraphics(plosFig, plosProbe, Resolution = plosDPI);
    plosImg = imread(plosProbe);

    [plosH, plosWpx, ~] = size(plosImg);
    plosScale = min([plosMaxW / plosWpx, plosMaxH / plosH, 1]);
    if plosScale < 1
        plosTarget = [min(floor(plosH * plosScale), plosMaxH), ...
                      min(floor(plosWpx * plosScale), plosMaxW)];
        plosImg = imresize(plosImg, plosTarget, "lanczos3");
    end
    imwrite(plosImg, plosOut, Compression = "lzw", Resolution = plosDPI);

    % Elsevier asks 1000 dpi for bitmapped line art, or vector.  Write the
    % vector PDF alongside the TIFF so the submission can use either.
    exportgraphics(plosFig, strrep(plosOut, ".tif", ".pdf"), ContentType = "vector");

    plosInfo = imfinfo(plosOut);
    plosOK = plosInfo.Width <= plosMaxW && plosInfo.Height <= plosMaxH ...
             && plosInfo.XResolution >= plosDPI;
    plosReport(plosK) = sprintf("  %-5s %5d x %4d px  %5.2f MB  %s  font %4.1f -> %.1f pt  %s", ...
        plosJobs(plosK, 2), plosInfo.Width, plosInfo.Height, ...
        dir(plosOut).bytes / 1e6, plosInfo.Compression, ...
        plosFont, plosFont * plosScale, string(plosOK));
end

close all force;
fprintf("\n=== JTB figure export summary ===\n%s\n", plosReport);
fprintf("\nAll compliant: %d\n", ~any(contains(plosReport, "false")));
